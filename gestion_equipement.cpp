// CREATE - Add new equipment
void Gestion_Equipement::on_btn_ajout_clicked()
{
    if (!validateInput()) {
        return;
    }
    
    // Generate next ID
    int newId = generateNextId();
    
    QSqlQuery query;
    query.prepare("INSERT INTO EQUIPEMENT (ID_EQUIPEMENT, NOM, CATEGORIE, QUANTITE_TOTALE, QUANTITE_DISPONIBLE, ETAT, FOURNISSEUR, DATE_ACQUISITION) "
                  "VALUES (:id, :nom, :categorie, :qteTotale, :qteDispo, :etat, :fournisseur, TO_DATE(:dateAcq, 'YYYY-MM-DD'))");
    
    query.bindValue(":id", newId);
    query.bindValue(":nom", ui->nom_equipement->toPlainText().trimmed());
    query.bindValue(":categorie", ui->comboBox_equipement->currentText());
    query.bindValue(":qteTotale", ui->spinBox_equipement->value());
    query.bindValue(":qteDispo", ui->spinBox_equipement1->value());
    query.bindValue(":etat", ui->comboBox->currentText());
    query.bindValue(":fournisseur", ui->nom_equipement_2->toPlainText().trimmed());
    query.bindValue(":dateAcq", ui->dateEdit->date().toString("yyyy-MM-dd"));
    
    if (query.exec()) {
        QMessageBox::information(this, "Succès", "Équipement ajouté avec succès!");
        loadTableData();
        clearForm();
    } else {
        QMessageBox::critical(this, "Erreur", "Erreur lors de l'ajout: " + query.lastError().text());
    }
}

// READ - Load data into table
void Gestion_Equipement::loadTableData()
{
    QSqlQuery query("SELECT ID_EQUIPEMENT, NOM, CATEGORIE, QUANTITE_TOTALE, QUANTITE_DISPONIBLE, ETAT, FOURNISSEUR, DATE_ACQUISITION FROM EQUIPEMENT");
    
    ui->tab_2->setRowCount(0);
    ui->tab_2->setColumnCount(8);
    
    QStringList headers;
    headers << "ID" << "Nom" << "Catégorie" << "Qté Totale" << "Qté Dispo" << "État" << "Fournisseur" << "Date Acquisition";
    ui->tab_2->setHorizontalHeaderLabels(headers);
    
    int row = 0;
    while (query.next()) {
        ui->tab_2->insertRow(row);
        
        for (int col = 0; col < 8; col++) {
            QTableWidgetItem *item = new QTableWidgetItem(query.value(col).toString());
            if (col == 0) { // ID column - read only
                item->setFlags(item->flags() & ~Qt::ItemIsEditable);
            }
            ui->tab_2->setItem(row, col, item);
        }
        row++;
    }
    
    // Adjust column widths
    ui->tab_2->resizeColumnsToContents();
}

// UPDATE - Modify existing equipment
void Gestion_Equipement::on_pushButton_4_clicked()
{
    QString id = ui->id_equipement->toPlainText().trimmed();
    
    if (id.isEmpty()) {
        QMessageBox::warning(this, "Attention", "Veuillez sélectionner un équipement à modifier.");
        return;
    }
    
    if (!validateInput()) {
        return;
    }
    
    QSqlQuery query;
    query.prepare("UPDATE EQUIPEMENT SET NOM=:nom, CATEGORIE=:categorie, QUANTITE_TOTALE=:qteTotale, "
                  "QUANTITE_DISPONIBLE=:qteDispo, ETAT=:etat, FOURNISSEUR=:fournisseur, DATE_ACQUISITION=TO_DATE(:dateAcq, 'YYYY-MM-DD') "
                  "WHERE ID_EQUIPEMENT=:id");
    
    query.bindValue(":id", id.toInt());
    query.bindValue(":nom", ui->nom_equipement->toPlainText().trimmed());
    query.bindValue(":categorie", ui->comboBox_equipement->currentText());
    query.bindValue(":qteTotale", ui->spinBox_equipement->value());
    query.bindValue(":qteDispo", ui->spinBox_equipement1->value());
    query.bindValue(":etat", ui->comboBox->currentText());
    query.bindValue(":fournisseur", ui->nom_equipement_2->toPlainText().trimmed());
    query.bindValue(":dateAcq", ui->dateEdit->date().toString("yyyy-MM-dd"));
    
    if (query.exec()) {
        QMessageBox::information(this, "Succès", "Équipement modifié avec succès!");
        loadTableData();
        clearForm();
    } else {
        QMessageBox::critical(this, "Erreur", "Erreur lors de la modification: " + query.lastError().text());
    }
}

// DELETE - Remove equipment
void Gestion_Equipement::on_pushButton_3_clicked()
{
    QString id = ui->id_equipement->toPlainText().trimmed();
    
    if (id.isEmpty()) {
        QMessageBox::warning(this, "Attention", "Veuillez sélectionner un équipement à supprimer.");
        return;
    }
    
    QMessageBox::StandardButton reply;
    reply = QMessageBox::question(this, "Confirmation", 
                                  "Êtes-vous sûr de vouloir supprimer cet équipement?",
                                  QMessageBox::Yes | QMessageBox::No);
    
    if (reply == QMessageBox::Yes) {
        QSqlQuery query;
        query.prepare("DELETE FROM EQUIPEMENT WHERE ID_EQUIPEMENT=:id");
        query.bindValue(":id", id.toInt());
        
        if (query.exec()) {
            QMessageBox::information(this, "Succès", "Équipement supprimé avec succès!");
            loadTableData();
            clearForm();
        } else {
            QMessageBox::critical(this, "Erreur", "Erreur lors de la suppression: " + query.lastError().text());
        }
    }
}

