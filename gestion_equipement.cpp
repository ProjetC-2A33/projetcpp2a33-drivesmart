// ==================== SEARCH AND FILTER ====================

void Gestion_Equipement::on_recherche_2_textChanged()
{
    QString searchText = ui->recherche_2->toPlainText().trimmed();
    
    if (searchText.isEmpty()) {
        loadTableData();
        return;
    }
    
    QSqlQuery query;
    query.prepare("SELECT ID_EQUIPEMENT, NOM, CATEGORIE, QUANTITE_TOTALE, QUANTITE_DISPONIBLE, ETAT, FOURNISSEUR, DATE_ACQUISITION "
                  "FROM EQUIPEMENT WHERE NOM LIKE :search OR FOURNISSEUR LIKE :search OR CATEGORIE LIKE :search");
    query.bindValue(":search", "%" + searchText + "%");
    
    ui->tab_2->setRowCount(0);
    
    if (query.exec()) {
        int row = 0;
        while (query.next()) {
            ui->tab_2->insertRow(row);
            
            for (int col = 0; col < 8; col++) {
                QTableWidgetItem *item = new QTableWidgetItem(query.value(col).toString());
                if (col == 0) {
                    item->setFlags(item->flags() & ~Qt::ItemIsEditable);
                }
                ui->tab_2->setItem(row, col, item);
            }
            row++;
        }
    }
}

void Gestion_Equipement::on_tri_2_currentIndexChanged(int index)
{
    QString orderBy;
    
    switch(index) {
        case 0: // Default
            loadTableData();
            return;
        case 1: // Name A-Z
            orderBy = "NOM ASC";
            break;
        case 2: // Name Z-A
            orderBy = "NOM DESC";
            break;
        case 3: // Qté Dispo croissant
            orderBy = "QUANTITE_DISPONIBLE ASC";
            break;
        case 4: // Qté Dispo décroissant
            orderBy = "QUANTITE_DISPONIBLE DESC";
            break;
        default:
            loadTableData();
            return;
    }
    
    QSqlQuery query;
    query.prepare(QString("SELECT ID_EQUIPEMENT, NOM, CATEGORIE, QUANTITE_TOTALE, QUANTITE_DISPONIBLE, ETAT, FOURNISSEUR, DATE_ACQUISITION "
                          "FROM EQUIPEMENT ORDER BY %1").arg(orderBy));
    
    ui->tab_2->setRowCount(0);
    
    if (query.exec()) {
        int row = 0;
        while (query.next()) {
            ui->tab_2->insertRow(row);
            
            for (int col = 0; col < 8; col++) {
                QTableWidgetItem *item = new QTableWidgetItem(query.value(col).toString());
                if (col == 0) {
                    item->setFlags(item->flags() & ~Qt::ItemIsEditable);
                }
                ui->tab_2->setItem(row, col, item);
            }
            row++;
        }
    }
}

// ==================== EXPORT FUNCTION ====================

void Gestion_Equipement::on_pushButton_17_clicked()
{
    // Export to CSV
    QString fileName = QFileDialog::getSaveFileName(this, "Exporter en CSV", "", "CSV Files (*.csv)");
    
    if (fileName.isEmpty()) {
        return;
    }
    
    QFile file(fileName);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        QMessageBox::critical(this, "Erreur", "Impossible d'ouvrir le fichier pour l'écriture.");
        return;
    }
    
    QTextStream out(&file);
    
    // Write headers
    out << "ID,Nom,Catégorie,Quantité Totale,Quantité Disponible,État,Fournisseur,Date Acquisition\n";
    
    // Write data
    for (int row = 0; row < ui->tab_2->rowCount(); ++row) {
        for (int col = 0; col < ui->tab_2->columnCount(); ++col) {
            QTableWidgetItem *item = ui->tab_2->item(row, col);
            if (item) {
                out << "\"" << item->text() << "\"";
            }
            if (col < ui->tab_2->columnCount() - 1) {
                out << ",";
            }
        }
        out << "\n";
    }
    
    file.close();
    QMessageBox::information(this, "Succès", "Données exportées avec succès!");
}
