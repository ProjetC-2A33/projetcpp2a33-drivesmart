void Gestion_Equipement::on_btnUpdateMaintenance_clicked()
{
    // Check maintenance status based on equipment condition
    QSqlQuery query("SELECT COUNT(*) FROM EQUIPEMENT WHERE ETAT = 'En maintenance' OR ETAT = 'Hors service'");
    
    int maintenanceCount = 0;
    QSqlQuery totalQuery("SELECT COUNT(*) FROM EQUIPEMENT");
    int totalCount = 0;
    
    if (query.next()) {
        maintenanceCount = query.value(0).toInt();
    }
    
    if (totalQuery.next()) {
        totalCount = totalQuery.value(0).toInt();
    }
    
    if (totalCount > 0) {
        int percentage = ((totalCount - maintenanceCount) * 100) / totalCount;
        ui->progressBar->setValue(percentage);
        
        if (percentage >= 80) {
            ui->label_12->setText("Statut : ✓ À jour");
            ui->label_12->setStyleSheet("color: green; font-weight: bold;");
        } else if (percentage >= 50) {
            ui->label_12->setText("Statut : ⚠ Attention requise");
            ui->label_12->setStyleSheet("color: orange; font-weight: bold;");
        } else {
            ui->label_12->setText("Statut : ✗ Maintenance urgente");
            ui->label_12->setStyleSheet("color: red; font-weight: bold;");
        }
        
        QMessageBox::information(this, "Maintenance", 
                                QString("Statut mis à jour!\n%1 équipements sur %2 sont opérationnels.")
                                .arg(totalCount - maintenanceCount)
                                .arg(totalCount));
    }
}

void Gestion_Equipement::on_btnCheckWeather_clicked()
{
    QString ville = ui->lineEditVille->toPlainText().trimmed();
    
    if (ville.isEmpty()) {
        QMessageBox::warning(this, "Attention", "Veuillez entrer un nom de ville.");
        return;
    }
    
    // Note: For a real implementation, you would need an API key from a weather service
    // This is a simplified example showing the structure
    
    QNetworkAccessManager *manager = new QNetworkAccessManager(this);
    
    // Example using OpenWeatherMap API (you need to replace YOUR_API_KEY)
    QString apiKey = "YOUR_API_KEY"; // Get a free key from openweathermap.org
    QString url = QString("http://api.openweathermap.org/data/2.5/weather?q=%1&appid=%2&units=metric&lang=fr")
                      .arg(ville)
                      .arg(apiKey);
    
    QNetworkRequest request(url);
    QNetworkReply *reply = manager->get(request);
    
    connect(reply, &QNetworkReply::finished, [this, reply]() {
        if (reply->error() == QNetworkReply::NoError) {
            QByteArray response = reply->readAll();
            QJsonDocument jsonDoc = QJsonDocument::fromJson(response);
            QJsonObject jsonObj = jsonDoc.object();
            
            if (jsonObj.contains("main")) {
                QJsonObject main = jsonObj["main"].toObject();
                double temp = main["temp"].toDouble();
                
                QJsonArray weatherArray = jsonObj["weather"].toArray();
                QString description = "N/A";
                if (!weatherArray.isEmpty()) {
                    description = weatherArray[0].toObject()["description"].toString();
                }
                
                ui->labelWeatherResult->setText(QString("Température: %1°C\nConditions: %2")
                                                .arg(temp, 0, 'f', 1)
                                                .arg(description));
            }
        } else {
            // Fallback display if API is not configured
            ui->labelWeatherResult->setText("Température: 20°C\n(Configuration API requise pour données réelles)");
            QMessageBox::information(this, "Info", "Pour obtenir des données météo réelles, configurez une clé API OpenWeatherMap.");
        }
        reply->deleteLater();
    });
}

