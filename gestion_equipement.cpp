bool Gestion_Equipement::validateInput()
{
    if (ui->nom_equipement->toPlainText().trimmed().isEmpty()) {
        QMessageBox::warning(this, "Validation", "Le nom de l'équipement est requis.");
        return false;
    }
    
    if (ui->nom_equipement_2->toPlainText().trimmed().isEmpty()) {
        QMessageBox::warning(this, "Validation", "Le fournisseur est requis.");
        return false;
    }
    
    if (ui->spinBox_equipement->value() <= 0) {
        QMessageBox::warning(this, "Validation", "La quantité totale doit être supérieure à 0.");
        return false;
    }
    
    if (ui->spinBox_equipement1->value() > ui->spinBox_equipement->value()) {
        QMessageBox::warning(this, "Validation", "La quantité disponible ne peut pas dépasser la quantité totale.");
        return false;
    }
    
    return true;
}

int Gestion_Equipement::generateNextId()
{
    // Find the smallest available ID
    QSqlQuery query("SELECT ID_EQUIPEMENT FROM EQUIPEMENT ORDER BY ID_EQUIPEMENT ASC");
    
    int expectedId = 1;
    while (query.next()) {
        int currentId = query.value(0).toInt();
        if (currentId != expectedId) {
            // Found a gap, return the missing ID
            return expectedId;
        }
        expectedId++;
    }
    
    // No gaps found, return the next sequential ID
    return expectedId;
}

