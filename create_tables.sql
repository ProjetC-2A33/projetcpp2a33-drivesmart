-- Script SQL pour créer toutes les tables nécessaires pour DriveSmart
-- Base de données Oracle

-- Table CONDIDAT (Candidats)
CREATE TABLE CONDIDAT (
    cin_condidat NUMBER(8) PRIMARY KEY,
    nom VARCHAR2(100) NOT NULL,
    prenom VARCHAR2(100) NOT NULL,
    sexe VARCHAR2(1) NOT NULL CHECK (sexe IN ('H', 'F')),
    date_naissance DATE NOT NULL,
    tel NUMBER(8) NOT NULL,
    type_permis VARCHAR2(50) NOT NULL
);

-- Table VEHICULE
CREATE TABLE VEHICULE (
    MATRICULE VARCHAR2(20) PRIMARY KEY,
    MODELE VARCHAR2(100) NOT NULL,
    KILOMETRAGE NUMBER(10) NOT NULL,
    DISPONIBILITE VARCHAR2(20) NOT NULL CHECK (DISPONIBILITE IN ('Libre', 'Réservé', 'En service')),
    TYPE_ENERGIE VARCHAR2(50) NOT NULL,
    ETAT_MAINTENANCE VARCHAR2(50) NOT NULL,
    DATE_MAINTENANCE DATE NOT NULL
);

-- Table EXAMEN
CREATE TABLE EXAMEN (
    ID_EXAMEN VARCHAR2(50) PRIMARY KEY,
    TYPE_EXAMEN VARCHAR2(50) NOT NULL CHECK (TYPE_EXAMEN IN ('code', 'conduit')),
    TYPE_PERMIS VARCHAR2(50) NOT NULL,
    DATE_EXAMEN DATE NOT NULL
);

-- Table EMPLOYEE (Moniteurs/Employés)
CREATE TABLE EMPLOYEE (
    ID_EMPLOYEE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    PRENOM VARCHAR2(100) NOT NULL,
    CIN NUMBER(8) UNIQUE,
    TEL NUMBER(8),
    EMAIL VARCHAR2(100),
    DATE_EMBAUCHE DATE,
    POSTE VARCHAR2(50)
);

-- Table PLANNING (Séances de conduite)
CREATE TABLE PLANNING (
    "ID_SÉANCE" NUMBER PRIMARY KEY,
    "DATE_SEANCE" DATE NOT NULL,
    "NOM_CANDIDAT" VARCHAR2(200),
    "TYPE_SÉANCE" VARCHAR2(50) NOT NULL CHECK ("TYPE_SÉANCE" IN ('code', 'conduit')),
    "HEURE_DEBUT" TIMESTAMP NOT NULL,
    "HEURE_FIN" VARCHAR2(10) NOT NULL,
    "ADRESSE_CIRCUIT" VARCHAR2(200) NOT NULL,
    "NOM_MONITEUR" VARCHAR2(200),
    "VEHICULE" VARCHAR2(20),
    CONSTRAINT FK_PLANNING_VEHICULE FOREIGN KEY ("VEHICULE") REFERENCES VEHICULE(MATRICULE)
);

-- Séquence pour générer les IDs de séance
CREATE SEQUENCE SEQ_PLANNING
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Alternative séquence (au cas où)
CREATE SEQUENCE SEQ_PLANNING_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Index pour améliorer les performances
CREATE INDEX IDX_PLANNING_DATE ON PLANNING("DATE_SEANCE");
CREATE INDEX IDX_PLANNING_CANDIDAT ON PLANNING("NOM_CANDIDAT");
CREATE INDEX IDX_PLANNING_MONITEUR ON PLANNING("NOM_MONITEUR");
CREATE INDEX IDX_CONDIDAT_CIN ON CONDIDAT(cin_condidat);
CREATE INDEX IDX_VEHICULE_MATRICULE ON VEHICULE(MATRICULE);

-- Commentaires sur les tables
COMMENT ON TABLE CONDIDAT IS 'Table des candidats pour le permis de conduire';
COMMENT ON TABLE VEHICULE IS 'Table des véhicules de l''auto-école';
COMMENT ON TABLE EXAMEN IS 'Table des examens de code et de conduite';
COMMENT ON TABLE EMPLOYEE IS 'Table des employés/moniteurs de l''auto-école';
COMMENT ON TABLE PLANNING IS 'Table de planification des séances de conduite';

